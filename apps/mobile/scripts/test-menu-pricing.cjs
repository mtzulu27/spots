const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../lib/menu-pricing.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const loaded = { exports: {} };
new Function('exports', 'require', 'module', compiled)(loaded.exports, require, loaded);
const { summarizePrices, estimateMenuTotal } = loaded.exports;
const catalog = JSON.parse(fs.readFileSync(path.join(__dirname, '../public/spots-catalog.json'), 'utf8'));
const branch = catalog.branches.find(row => row.id === 1931);
const items = branch.menu_items;
assert.equal(items.length, 75);
assert.equal(items.filter(item => item.calculationIncluded).length, 51);
assert.equal(items.find(item => item.name === 'Don Julio 1942').price, 1600000);
assert.equal(items.find(item => item.name === 'Don Julio 1942').calculationIncluded, false);
const summaries = Object.fromEntries(['mains', 'drinks', 'starters', 'desserts'].map(key => [key, summarizePrices(items, key)]));
assert.deepEqual(summaries.mains, { minimum: 37000, maximum: 96000, average: 60625, sampleSize: 8 });
assert.equal(summaries.drinks.maximum, 50000);
assert.equal(summaries.drinks.sampleSize, 33);
assert.equal(Math.round(estimateMenuTotal(['mains', 'drinks'], { mains: 1, drinks: 1 }, summaries)), branch.typical_budget);
assert.equal(estimateMenuTotal(['mains', 'drinks'], { mains: 0, drinks: 0 }, summaries), 0);
assert.equal(estimateMenuTotal(['cover', 'drinks'], { cover: 1, drinks: 1 }, summaries), null);
assert.equal(estimateMenuTotal(['cover'], { cover: 0 }, {}), 0);
assert.equal(summarizePrices([], 'drinks'), null);
assert.equal(summarizePrices([{ name: 'Unknown', category: 'drinks', price: NaN }], 'drinks'), null);
assert.equal(summarizePrices([{ name: 'Explicitly free', category: 'tickets', price: 0 }], 'tickets').average, 0);
const before = JSON.parse(fs.readFileSync(path.join(__dirname, '../../..', 'docs/catalog-review/agave-azul-cocina-bar-2026-09-05/before.json'), 'utf8'));
const spot = catalog.spots.find(row => row.id === branch.spot_id);
for (const key of ['id', 'slug', 'created_at', 'logo_url']) assert.deepEqual(spot[key], before.spot[key]);
const approvedPhotos = JSON.parse(fs.readFileSync(path.join(__dirname, '../../..', 'docs/catalog-review/agave-azul-cocina-bar-2026-09-05/user-photos.json'), 'utf8'));
assert.equal(spot.cover_image_url, approvedPhotos.after.cover_image_url);
assert.deepEqual(spot.gallery_urls, approvedPhotos.after.gallery_urls);
assert.equal(branch.google_maps_url, 'https://maps.app.goo.gl/5pDUoZDedtMRyBc99');
assert.equal(catalog.branchHours.filter(row => row.branch_id === branch.id).length, 7);
assert.equal(branch.holiday_mode, 'inherit');
console.log('Menu pricing, missing-price, presentation, schedule and preserved-photo checks passed');
